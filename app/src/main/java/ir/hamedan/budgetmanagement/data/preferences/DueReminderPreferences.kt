package ir.hamedan.budgetmanagement.data.preferences

import android.content.Context

/**
 * فقط یک وظیفه دارد: مشخص می‌کند که آیا دیالوگ یادآوری سررسید بدهی/طلب
 * (در HomeScreen) در همین اجرای برنامه (Session) قبلاً یک‌بار به کاربر
 * نشان داده شده یا نه.
 *
 * رفتار جدید طبق درخواست:
 * ۱. هر بار که کاربر برنامه را باز می‌کند (یعنی پروسه‌ی اپ از نو اجرا می‌شود)
 *    باید دوباره بررسی شود که آیا در ۳ روز آینده بدهی/طلبی سررسید دارد یا نه؛
 *    اگر داشت، دیالوگ باید نمایش داده شود. یعنی این پرچم دیگر نباید برای
 *    همیشه (بین بازکردن‌های مختلف اپ) پایدار بماند، مثل حالت قبلی که فقط
 *    یک‌بار در کل عمر نصبِ اپ نمایش داده می‌شد.
 * ۲. اما در همان یک بار بازبودن اپ، اگر کاربر از HomeScreen به صفحه‌ی
 *    دیگری برود و دوباره برگردد، نباید دیالوگ دوباره نمایش داده شود.
 *
 * برای برآوردن هر دو شرط، پرچم دیگر در SharedPreferences (که بین اجراهای
 * مختلف پروسه‌ی اپ هم پایدار می‌ماند) ذخیره نمی‌شود؛ بلکه به‌صورت یک
 * متغیر درون‌حافظه‌ای (in-memory) در همین singleton نگه داشته می‌شود.
 * این singleton به اندازه‌ی طول عمر پروسه‌ی اپلیکیشن زنده است:
 * - با هر بار کشتن و دوباره بازکردن اپ (اجرای پروسه‌ی جدید)، این مقدار
 *   خودکار به false ریست می‌شود ← دیالوگ دوباره (در صورت وجود مورد
 *   سررسیدشده) نمایش داده می‌شود.
 * - با جابه‌جایی صرف بین صفحات در همان اجرای اپ (پروسه عوض نمی‌شود)
 *   مقدار true باقی می‌ماند ← دیالوگ دوباره نمایش داده نمی‌شود.
 *
 * امضای توابع (با پارامتر Context) عمداً همان قبلی نگه داشته شده تا
 * محل‌های صدازننده (مثل HomeScreen) نیازی به تغییر نداشته باشند؛
 * خودِ Context دیگر استفاده‌ی عملی ندارد و صرفاً برای سازگاری با
 * امضای قبلی نگه داشته شده است.
 */
object DueReminderPreferences {

    // این پرچم فقط در حافظه نگه داشته می‌شود، نه در Disk/SharedPreferences.
    // بنابراین با هر بار اجرای تازه‌ی پروسه‌ی اپ (باز کردن مجدد اپ) به
    // مقدار پیش‌فرض false بازمی‌گردد.
    @Volatile
    private var hasShownThisSession: Boolean = false

    fun hasShownOnce(context: Context): Boolean {
        return hasShownThisSession
    }

    fun markShownOnce(context: Context) {
        hasShownThisSession = true
    }
}